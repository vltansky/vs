// Regenerates the inline catalog and review overlay in every template shell
// (artifact.html, proposal.html). Run after changing either source module;
// the corresponding static eval fails on drift.
//
//   node assets/sync-artifact-catalog.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { vsLayoutCss, vsCatalogFactory } = await import('./definitions.mjs');
const { artifactToolRegistryFactory, resolveQuoteStart, reviewOverlayCss, reviewOverlayFactory, reviewStorageKey, reviewToolFactory } = await import('./review-overlay.mjs');

// The factory source is inlined verbatim so the drift test can compare it with
// Function.prototype.toString. The css is escaped defensively; today it holds
// no backticks or ${, and the escape keeps a future edit from breaking the tag.
const escapeTemplateLiteral = (value) => value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const escapedCss = escapeTemplateLiteral(vsLayoutCss);

const block = [
  '// vs-catalog:begin (generated by sync-artifact-catalog.mjs - do not edit)',
  `const vsLayoutCss = \`${escapedCss}\`;`,
  `const vsCatalogFactory = ${vsCatalogFactory.toString()};`,
  'const vsCatalog = vsCatalogFactory(window.Htmdx.React, vsLayoutCss);',
  'for (const theme of vsCatalog.themes) window.Htmdx.registerTheme(theme);',
  'window.Htmdx.registerComponents(vsCatalog.components, { rerender: false });',
  // The layout registers last: registerLayout rerenders by default, so one
  // rerender picks up the theme, the components, and the layout together.
  'for (const layout of vsCatalog.layouts) window.Htmdx.registerLayout(layout);',
  '// vs-catalog:end',
].join('\n');

const pattern = /\/\/ vs-catalog:begin[\s\S]*?\/\/ vs-catalog:end/;
const reviewBlock = [
  '// vs-review:begin (generated by sync-artifact-catalog.mjs - do not edit)',
  `const reviewOverlayCss = \`${escapeTemplateLiteral(reviewOverlayCss)}\`;`,
  `const resolveQuoteStart = ${resolveQuoteStart.toString()};`,
  `const reviewStorageKey = ${reviewStorageKey.toString()};`,
  `const reviewToolFactory = ${reviewToolFactory.toString()};`,
  `const artifactToolRegistryFactory = ${artifactToolRegistryFactory.toString()};`,
  `const reviewOverlayFactory = ${reviewOverlayFactory.toString()};`,
  'reviewOverlayFactory(reviewOverlayCss, resolveQuoteStart, reviewToolFactory, artifactToolRegistryFactory, reviewStorageKey);',
  '// vs-review:end',
].join('\n');
const reviewPattern = /<script>\s*\/\/ vs-(?:webmcp:begin[\s\S]*?webmcp:end|review:begin[\s\S]*?review:end)\s*<\/script>/;
for (const template of ['artifact.html', 'proposal.html']) {
  const templatePath = join(here, template);
  const shell = readFileSync(templatePath, 'utf8');
  if (!pattern.test(shell)) {
    console.error(`${template} has no vs-catalog:begin/end markers to replace`);
    process.exit(2);
  }
  if (!reviewPattern.test(shell)) {
    console.error(`${template} has no review or legacy WebMCP block to replace`);
    process.exit(2);
  }
  writeFileSync(
    templatePath,
    shell.replace(pattern, block).replace(reviewPattern, `<script>\n${reviewBlock}\n    </script>`),
  );
  console.log(`${template} catalog and review blocks regenerated`);
}
