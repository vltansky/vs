// Builds the cleanup shell script. Single source for both the page (scan.mts inlines it,
// stripping `export`) and cleanup.mts, so the browser and CLI emit identical scripts.
export function buildScript(items, { scannedAt, prompt = true, scanCmd }) {
  const gb = (kb) => (kb >= 1048576 ? (kb / 1048576).toFixed(1) + ' GB' : Math.round(kb / 1024) + ' MB');
  const total = items.reduce((s, i) => s + i.kb, 0);
  const L = ['#!/usr/bin/env bash',
    `# Generated by vs-disk-cleanup/disk-report on ${new Date().toISOString()} from scan ${scannedAt}`,
    `# ${items.length} items, ~${gb(total)}. Read it, then run: bash cleanup.sh`,
    "# Uses each tool's own clean command where one exists.",
    '# rm_regen: permanent delete of regenerable dirs; inside a git repo only if git-ignored (some repos commit node_modules).',
    '# rm_safe:  moves to Trash (review items: recoverable until Trash is emptied).',
    'set -u',
    'vol=/System/Volumes/Data; before=$(df -k "$vol" | awk \'END{print $4}\')',
    'rm_safe() { [ -e "$1" ] || return 0; if command -v trash >/dev/null; then trash "$1"; else mv "$1" "$HOME/.Trash/"; fi; }',
    'rm_regen() {',
    '  [ -e "$1" ] || return 0',
    '  local dir; dir=$(dirname "$1")',
    '  if git -C "$dir" rev-parse --is-inside-work-tree >/dev/null 2>&1 && ! git -C "$dir" check-ignore -q "$1"; then',
    '    echo "  SKIP not git-ignored: $1"; return 0',
    '  fi',
    '  rm -rf "$1"',
    '}', ''];
  if (prompt) L.push(`read -r -p "Clean ${items.length} items (~${gb(total)})? [y/N] " ok; [ "$ok" = "y" ] || { echo "Aborted, nothing changed."; exit 1; }`, '');
  for (const it of items) {
    L.push(`echo "== ${it.label.replace(/"/g, '\\"')} (${gb(it.kb)}, ${it.group})"`);
    L.push(...it.commands, '');
  }
  L.push('after=$(df -k "$vol" | awk \'END{print $4}\')',
    'echo; echo "Freed $(( (after - before) / 1024 )) MB; free now: $(df -h "$vol" | awk \'END{print $4}\'). Trashed items free space only after Trash is emptied."',
    `echo "Re-scan: node ${scanCmd ?? '<vs-disk-cleanup>/scripts/disk-report/scan.mts'}"`);
  return L.join('\n') + '\n';
}
